/** Replaces the first exact occurrence of `from`; throws when missing. */
function replaceExact(source, from, to, label) {
  const idx = source.indexOf(from);
  if (idx === -1) {
    throw new Error(`build_tor: anchor not found (${label}). The root source changed — update tools/build_tor.js.`);
  }
  return source.slice(0, idx) + to + source.slice(idx + from.length);
}

/**
 * Replaces everything from `startMarker` (inclusive) up to `endMarker`
 * (exclusive) with `replacement`; throws when either marker is missing.
 */
function replaceSection(source, startMarker, endMarker, replacement, label) {
  const s = source.indexOf(startMarker);
  if (s === -1) {
    throw new Error(`build_tor: section start not found (${label}). Update tools/build_tor.js.`);
  }
  const e = source.indexOf(endMarker, s);
  if (e === -1) {
    throw new Error(`build_tor: section end not found (${label}). Update tools/build_tor.js.`);
  }
  return source.slice(0, s) + replacement + source.slice(e);
}

function readNative(name) {
  return fs.readFileSync(path.join(NATIVE, name), 'utf8');
}

// ---------------------------------------------------------------------------
// manifest.json
// ---------------------------------------------------------------------------

function buildManifest(sourceJson) {
  const manifest = JSON.parse(sourceJson);

  // 1. Background: Firefox MV3 has no service workers — use an event page.
  //    Storage.js must load first because the native background.js expects
  //    AppStorage to be available.
  manifest.background = {
    scripts: ['src/storage/Storage.js', 'background.js']
  };

  // 2. options_page is Chrome-only; Firefox requires options_ui.
  if (manifest.options_page) {
    manifest.options_ui = {
      page: manifest.options_page,
      open_in_tab: true
    };
    delete manifest.options_page;
  }

  // 3. Firefox requires an explicit add-on id for unsigned/sideloaded MV3.
  manifest.browser_specific_settings = {
    gecko: {
      id: GECKO_ID,
      strict_min_version: GECKO_MIN_VERSION
    }
  };

  return JSON.stringify(manifest, null, 2) + '\n';
}

