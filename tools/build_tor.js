/** Recursively lists files under dir, returning paths relative to dir. */
function listFiles(dir) {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      out.push(...listFiles(full).map((p) => path.join(entry.name, p)));
    } else {
      out.push(entry.name);
    }
  }
  return out;
}

/**
 * Ensures no chrome.* API call survives in the generated JS. Identifiers
 * that merely start with "chrome" (chromeEl, chromeHideTimer), string
 * literals such as 'chrome://' and prose like "slideshow chrome. The"
 * do not match the tight `chrome.<ident>` pattern.
 */
function assertNoChromeApi(files) {
  const offenders = [];
  for (const [rel, content] of files) {
    if (!rel.endsWith('.js')) continue;
    const text = content.toString('utf8');
    const match = text.match(/(?<![A-Za-z0-9_$])chrome\.[A-Za-z_$]/);
    if (match) offenders.push(rel);
  }
  if (offenders.length) {
    throw new Error('build_tor: chrome.* API leaked into the native build: ' + offenders.join(', '));
  }
}

/** Computes the full { relativePath: Buffer } map for the tor/ tree. */
function buildTree() {
  const files = new Map();

  files.set('manifest.json', Buffer.from(buildManifest(fs.readFileSync(path.join(SRC, 'manifest.json'), 'utf8'))));
  files.set('README.md', Buffer.from(buildReadme()));

  for (const rel of COPY_FILES) {
    files.set(rel, fs.readFileSync(path.join(SRC, rel)));
  }
  for (const dir of COPY_DIRS) {
    for (const rel of listFiles(path.join(SRC, dir))) {
      const key = path.join(dir, rel);
      files.set(key, fs.readFileSync(path.join(SRC, key)));
    }
  }

  for (const [rel, nativeName] of Object.entries(NATIVE_REPLACEMENTS)) {
    files.set(rel, Buffer.from(readNative(nativeName)));
  }
  for (const [rel, transform] of Object.entries(TRANSFORMS)) {
    const source = fs.readFileSync(path.join(SRC, rel), 'utf8');
    files.set(rel, Buffer.from(transform(source)));
  }

  assertNoChromeApi(files);
  return files;
}

function main() {
  const check = process.argv.includes('--check');
  const tree = buildTree();

  if (check) {
    const problems = [];
    for (const [rel, content] of tree) {
      const dest = path.join(TARGET, rel);
      if (!fs.existsSync(dest)) {
        problems.push(`missing: tor/${rel}`);
      } else if (!fs.readFileSync(dest).equals(content)) {
        problems.push(`stale:   tor/${rel}`);
      }
    }
    // Detect orphan files left behind after renames/deletions in the source.
    if (fs.existsSync(TARGET)) {
      for (const rel of listFiles(TARGET)) {
        if (!tree.has(rel)) problems.push(`orphan:  tor/${rel}`);
      }
    }
    if (problems.length) {
      console.error('tor/ build is out of date. Run: npm run build:tor');
      problems.forEach((p) => console.error('  ' + p));
      process.exit(1);
    }
    console.log('tor/ build is up to date.');
    return;
  }

  // Clean rebuild so removed source files never linger in the output.
  fs.rmSync(TARGET, { recursive: true, force: true });
  for (const [rel, content] of tree) {
    const dest = path.join(TARGET, rel);
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.writeFileSync(dest, content);
  }
  console.log(`Wrote ${tree.size} files to ${path.relative(ROOT, TARGET)}/`);
}

if (require.main === module) main();

